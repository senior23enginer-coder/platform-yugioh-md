const assert = require("node:assert/strict");
const E = require("../assets/modules/play-calculator/engine.js");
const P = require("../assets/modules/play-calculator/planner.js");
const db = require("../assets/modules/play-calculator/card-facts.json");
const fixture = require("./fixtures/calculator_inventory.json");
const own = E.catalog(fixture.allDecks.find((d) => d.id === 665), fixture.cards);
const rival = E.catalog(fixture.allDecks.find((d) => d.id === 656), fixture.cards);
const source = E.create(own, rival);
const unchanged = JSON.stringify(source);
let s = E.appendChain(source, { side: "self", cardName: "Kashtira Fenrir", effect: "Activa efecto de búsqueda" });
s = E.appendChain(s, { side: "opponent", cardName: "", effect: "Respuesta conocida; identidad por confirmar" });
assert.equal(JSON.stringify(source), unchanged, "Capture cannot mutate previous scenario");
assert.deepEqual(s.chain.map((x) => x.link), [1, 2]);
assert.equal(s.chain[1].cardName, "");
const blocked = P.solve(s, db);
assert.equal(blocked.plans.length, 0);
assert.match(blocked.reason, /cadena pendiente/i);
s = E.removeChain(s, 1);
assert.deepEqual(s.chain.map((x) => x.link), [1]);
assert.equal(s.chain[0].side, "opponent");
s = E.removeChain(s, 1);
assert.equal(s.chain.length, 0);
assert.doesNotMatch(P.solve(s, db).reason, /cadena pendiente/i);
assert.throws(() => E.appendChain(s, { side: "self", effect: "" }), /Describe/);
assert.throws(() => E.appendChain(s, { side: "neither", effect: "x" }), /jugador/);
assert.throws(() => E.removeChain(s, 1), /inexistente/);
const view = require("node:fs").readFileSync(require("node:path").resolve(__dirname, "../assets/modules/play-calculator/ui.js"), "utf8");
for (const hook of ["data-chain-add", "data-chain-remove", "data-chain-effect", "data-chain-side"])
  assert(view.includes(hook), `Missing UI control ${hook}`);
console.log(JSON.stringify({ ok: true, chainCapture: true, immutable: true, pendingChainBlocksSearch: true }));
