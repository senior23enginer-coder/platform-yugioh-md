assert.equal(resolve(data,decks[0],{...league,ranking:league.ranking.map(r=>({...r,pj:0}))},division).label,'Sin clasificación');
assert.equal(resolve(data,decks[0],null,division).label,'Sin liga');
assert.equal(resolve(data,decks[0],{...league,status:'completed'},division).label,'Sin liga');
assert.equal(resolve(data,decks[0],{...league,active:0},division).label,'Sin liga');
assert.equal(resolve(data,decks[0],league,{...division,league_competition_id:99}).label,'Sin liga');
assert.equal(resolve(data,{id:99,division_id:10},league,division).label,'Sin clasificación');
assert.equal(resolve(data,decks[0],{...league,ranking:[{id:1,division_id:20,pj:1}]},division).label,'Sin clasificación');
assert.equal(resolve(data,decks[0],{...league,type:'cup'},division).label,'Sin liga');
assert.equal(resolve(data,decks[0],{...league,ranking:[{deck_id:2,matches:1},{deck_id:1,matches:0}]},division).position,2);
console.log(JSON.stringify({ok:true,serverOrderPreserved:true,divisionScoped:true,noSeedOrGlobalRatingFallback:true,unplayedDivision:true,inactiveLeague:true,foreignDeckExcluded:true}));
const {forMatch}=require('../assets/modules/deck-guide/league-position.js');
const match={competition_id:50,division_id:10,deck_a_id:1,deck_b_id:2};
const eventData={...data,competitions:[league],divisions:{first:division}};
