const assert=require('node:assert/strict');
const {resolve}=require('../assets/modules/deck-guide/league-position.js');
const decks=[{id:1,division_id:10},{id:2,division_id:10},{id:3,division_id:20},{id:4,division_id:30}];
const division={id:10,league_competition_id:50,name:'Primera División'};
const league={id:50,type:'league',name:'Liga Elite',active:1,status:'active',ranking:[{id:3,pj:2,position:1},{id:2,pj:1,position:2},{id:1,pj:0,position:3},{id:4,pj:8,position:4}]};
const data={allDecks:decks};
assert.equal(resolve(data,decks[0],league,division).label,'2.º de 2');
