assert.equal(forMatch({...eventData,competitions:[{...league,type:'cup'}]},match),null);
assert.equal(forMatch({...eventData,competitions:[{...league,status:'completed',active:0}]},match).a[0].position,2);
assert.equal(forMatch(eventData,{...match,division_id:99}).a[0].label,'Sin clasificación');
