assert.equal(forMatch(eventData,{...match,deck_a_id:99}).a[0].position,null);
// A historical ranking row explicitly determines its event division after a deck moves.
const moved={...eventData,allDecks:decks.map(d=>({...d,division_id:20})),competitions:[{...league,ranking:[{id:2,division_id:10,pj:2},{id:1,division_id:10,pj:2}]}]};
