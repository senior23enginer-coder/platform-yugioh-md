'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const app = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(app,p),'utf8');
const router = read('assets/source/javascript/17-deck-categories.js');
const workspace = read('assets/modules/play-calculator/workspace.js');
const calculator = read('assets/modules/play-calculator/ui.js');
const imageIndex = JSON.parse(read('assets/cards/originals/index.json'));
const crystron = JSON.parse(read('assets/editorial/20261117-folder-delivery-v40/677.json'));
assert(router.includes("category === 'play-calculator'") && router.includes("routeTo('calculadora_jugadas')"), 'Deck calculator must use standalone screen, never the modal');
assert(workspace.includes("stationx:calculator-deck") && workspace.includes("data-calculator-return-profile"), 'The standalone screen must restore the deck and offer return navigation');
assert(workspace.includes("select.dispatchEvent(new Event('change'))"), 'The restored deck must mount its board');
assert(!Object.keys(imageIndex.cards).some(key=>key.startsWith('677:')), 'Fixture requires Crystron absent from original-only index');
const sample = crystron.cards.find(card=>card.slots?.some(slot=>slot.section==='main') && /^\.\/assets\/editorial\//.test(card.image||''));
assert(sample,'Crystron has editorial photos with real native slots');
assert(calculator.includes('applyEditorialImages(selfStudy, native)'),'Resolve own photos from the active editorial record');
assert(calculator.includes('applyEditorialImages(otherStudy, scenario.opponent)'),'Also resolve opponent photos');
assert(calculator.includes('catalog.id + \':\' + Number(slot.card_id)'), 'Images must be associated by exact deck/slot key');
assert(calculator.includes('state.editorialImages[card.key] ||'),'Prefer current editorial photo before historical index');
console.log('Calculator standalone navigation and Crystron editorial image contract verified.');
