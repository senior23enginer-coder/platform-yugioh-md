const assert = require("node:assert/strict");
const T = require("../assets/modules/play-calculator/transitions.js");
const R = require("../assets/modules/play-calculator/rules.js");
assert.equal(T.version, 1);
assert.equal(T.assertDestination("hand"), "hand");
assert.throws(() => T.assertDestination("m1", { blockedZones: ["m1"] }), /Zona bloqueada/);
assert.throws(() => T.assertDestination("graveyard", {}, { graveyardBlocked: true }), /Cementerio/);
assert.throws(() => T.assertDestination("banished", {}, { banishBlocked: true }), /Destierro/);
assert.throws(() => T.assertDestination(null), /Destino/);
const token = { uid: 1, owner: "self", controller: "opponent", zone: "m1" };
assert.equal(T.destinationController(token, "graveyard"), "self");
assert.equal(T.destinationController(token, "extra"), "self");
assert.equal(T.destinationController(token, "m2"), "opponent");
assert.equal(T.destinationController(token, "hand"), "opponent", "Conserva semántica actual fuera de destinos de propietario");
assert.throws(() => T.destinationController({ owner: "nobody", controller: "self" }, "deck"), /controlador/);
const state = { tokens: [token, { uid: 2, controller: "self", zone: "m1" }] };
assert.equal(T.assertVacant(state, "self", "m2"), true);
assert.equal(T.assertVacant(state, "self", "m1", 2), true);
assert.throws(() => T.assertVacant(state, "self", "m1"), /ocupada/);
assert.equal(state.tokens[0].zone, "m1", "Validar una transición no debe modificar el estado");
assert.equal(typeof R.actions, "function");
