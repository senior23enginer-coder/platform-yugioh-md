'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const E = require('../assets/modules/play-calculator/engine.js');
const R = require('../assets/modules/play-calculator/rules.js');
const P = require('../assets/modules/play-calculator/planner.js');
const S = require('../assets/modules/play-calculator/study.js');
const Restrictions = require('../assets/modules/play-calculator/restrictions.js');
const facts = require('../assets/modules/play-calculator/card-facts.json');
const editorial = JSON.parse(fs.readFileSync(path.join(__dirname, '../assets/editorial/20261117-folder-delivery-v40/677.json'), 'utf8'));
assert.equal(editorial.deck_id, 677);
assert.equal(editorial.routes.length, 14, 'Preserve A09 Crystron routes');
assert.equal(editorial.cards.length, 39, 'Preserve approved card identities');
assert.equal(editorial.calculator.rules.length, 4, 'Two Horus and two Smiger portable rules');
const inventory = editorial.cards.flatMap(card => (card.slots || []).map(slot => ({
  id:slot.card_id, deck_id:677, card_name:card.name, section:slot.section, quantity:slot.quantity
})));
const native = E.catalog({id:677,name:'Crystron/Horus',format_codes:['tcg_advanced']}, inventory);
const db = S.bind(facts,[{catalog:native,study:editorial}]);
assert.equal(db.ruleImports[0].status, 'accepted', JSON.stringify(db.ruleImports));
assert.equal(db.ruleImports[0].count, 4);
const idField = '677:smiger:destroy-citree';
const idGrave = '677:smiger:graveyard-search';
const fieldRule = editorial.calculator.rules.find(r => r.id === idField);
const gyRule = editorial.calculator.rules.find(r => r.id === idGrave);
assert(fieldRule && gyRule && fieldRule.oncePerName && gyRule.oncePerName);
assert.equal(fieldRule.resolve[0].flag, 'machineSynchroOnly');
assert.equal(fieldRule.resolve[0].duration, 'turn');
assert.equal(fieldRule.resolve[1].op, 'destroy');
assert.equal(fieldRule.resolve[2].op, 'take');
assert.equal(fieldRule.resolve[2].cid, 12606);
assert.equal(gyRule.costs[0].to, 'banished');
assert.equal(gyRule.resolve[0].cid, 20798);
const add = (s,cid,zone,position='attack') => {
  const card = native.cards.find(c=>db.bindings[c.key]===cid);
  assert(card, 'Missing exact native CID '+cid);
  const uid=s.nextId;
  return E.position(E.place(s,{key:card.key,owner:'self',controller:'self',zone}),uid,position);
};
const actions = (s,id,options={}) => R.actions(s,db,options).actions.filter(a=>a.event?.ruleId===id);
let own=E.create(native);
own=add(own,12608,'m1');
const original=JSON.stringify(own);
const inspected=R.actions(own,db);
const field=inspected.actions.filter(action=>action.event?.ruleId===idField);
assert.equal(field.length,1,'Smiger can select itself, destroy itself and bring Citree: '+JSON.stringify(inspected.rejected.filter(x=>x.id===idField)));
const next=field[0].state;
assert.equal(JSON.stringify(own),original,'Calculator must never mutate the captured situation');
assert(next.tokens.some(t=>db.bindings[t.key]===12608&&t.zone==='graveyard'));
assert(next.tokens.some(t=>db.bindings[t.key]===12606&&/^m[1-5]$/.test(t.zone)));
assert.equal(next._ruleFlags.machineSynchroOnly,true);
assert.equal(next._ruleFlagTurns.machineSynchroOnly,next.turn);
assert.equal(next._ruleUseTurns['rule:cid:12608'],next.turn);
assert.equal(actions(next,idGrave).length,0,'Smiger cannot use GY effect in same turn as field effect');
assert.equal(actions(next,idField).length,0,'Smiger cannot activate field effect again this turn');
assert.equal(actions(own,idField,{specialBlocked:true}).length,0);
assert.equal(actions(own,idField,{graveyardBlocked:true}).length,0);
assert.equal(actions(own,idField,{blockedZones:['m1','m2','m3','m4','m5']}).length,0);
const facedown=E.clone(own);
facedown.tokens.find(t=>db.bindings[t.key]===12608).position='set';
assert.equal(actions(facedown,idField).length,0,'No face-down actor activation');
const noCitree=add(own,12606,'hand');
assert.equal(actions(noCitree,idField).length,0,'Cannot fabricate a tuner if all copies leave Main Deck');
let grave=E.create(native);
grave=add(grave,12608,'graveyard');
const beforeGY=JSON.stringify(grave);
const searched=actions(grave,idGrave);
assert.equal(searched.length,1,'Smiger GY should banish itself and add Inclusion');
assert.equal(JSON.stringify(grave),beforeGY);
const fetched=searched[0].state;
assert(fetched.tokens.some(t=>db.bindings[t.key]===12608&&t.zone==='banished'));
assert(fetched.tokens.some(t=>db.bindings[t.key]===20798&&t.zone==='hand'));
assert.equal(fetched._ruleUseTurns['rule:cid:12608'],fetched.turn);
assert.equal(actions(fetched,idGrave).length,0,'GY branch shares turn use');
assert.equal(actions(grave,idGrave,{banishBlocked:true}).length,0);
assert.equal(actions(grave,idGrave,{noDeckToHand:true}).length,0);
assert.equal(actions(grave,idGrave,{graveyardBlocked:true}).length,0);
let noInclusion=E.clone(grave);
for(let i=0;i<3;i++)noInclusion=add(noInclusion,20798,'graveyard');
assert.equal(actions(noInclusion,idGrave).length,0,'Search must not invent a missing card');
assert.equal(Restrictions.effective({...next,turn:next.turn+1}).machineSynchroOnly,undefined,
  'Machine Synchro restriction must expire after this turn');
assert.equal(Restrictions.effective(next).machineSynchroOnly,true);
const planned=P.solve(own,db,{depth:2,budget:250,width:40});
assert(planned.plans.some(plan=>plan.steps.some(step=>step.label.includes('Smiger en Campo'))),
  'The actual Analyze button must consider the supported field effect');
console.log('Crystron Smiger: field destruction, Tuner summon, GY search, shared use and time-bound lock passed.');
